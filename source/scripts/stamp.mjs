// Generates src/buildStamp.ts with the build time in IST. Runs as a prebuild hook.
import { writeFileSync } from 'node:fs';
const parts = Object.fromEntries(
  new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Asia/Kolkata', weekday: 'short', day: 'numeric', month: 'short',
    year: 'numeric', hour: 'numeric', minute: '2-digit', hour12: true,
  }).formatToParts(new Date()).map((p) => [p.type, p.value]),
);
const stamp = `${parts.weekday} ${parts.day} ${parts.month} ${parts.year}, ${parts.hour}:${parts.minute} ${parts.dayPeriod.toUpperCase()} IST`;
writeFileSync('src/buildStamp.ts', `// Generated by scripts/stamp.mjs at build time.\nexport const BUILD_AT = '${stamp}';\n`);
console.log('build stamp:', stamp);
